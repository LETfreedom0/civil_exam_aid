-- -----------------------------------------------------------------------------
-- 1. 批次层：一次公告 = 一条记录
--    旧代码里 exam_timelines 靠 (province_code, year, category) 三件套定位，
--    本质就是一个批次，这里把它正式建模出来。
-- -----------------------------------------------------------------------------
create table if not exists public.exam_cycles (
  id                bigint generated by default as identity primary key,
  province_code     text not null references public.provinces(code),
  year              integer not null,
  category          smallint not null default 0,   -- 0省考 1事业单位 2国考 3其他
  name              text,                          -- 2026年广西考试录用公务员
  announcement_title text,
  announcement_url  text,
  source_id         bigint,                        -- → data_sources.id

  -- 时间节点（全部 date，允许缺省）
  publish_date      date,   -- 公告发布
  signup_start      date,   -- 报名开始
  signup_end        date,   -- 报名结束
  payment_end       date,   -- 缴费截止
  admit_card_start  date,   -- 准考证打印开始
  exam_date         date,   -- 笔试开始
  exam_end_date     date,   -- 笔试结束
  score_date        date,   -- 成绩公布
  interview_start   date,   -- 面试开始
  interview_end     date,   -- 面试结束

  -- 状态由后台维护，前端不再用「月份大于 6 就算结束」这种猜测
  status            text not null default 'unknown'
                    check (status in ('unknown','upcoming','running','pending','examined','scored','finished')),

  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (province_code, year, category)
);

comment on table  public.exam_cycles is '公告批次：一个省一年一个考试类别 = 一次招录公告';
comment on column public.exam_cycles.category is '0省考 1事业单位 2国考 3其他';
comment on column public.exam_cycles.status  is '批次状态，供列表徽标直接读取，避免前端推算';

-- -----------------------------------------------------------------------------
-- 2. 岗位层：在原有 positions 上挂 cycle_id，其余字段原样保留
--    保留冗余的 province_code / year / position_origin 是有意的：
--    列表查询和 RLS 都按这三个字段过滤，避免每次 join 批次表。
-- -----------------------------------------------------------------------------
alter table public.positions
  add column if not exists cycle_id            bigint references public.exam_cycles(id) on delete set null,
  add column if not exists is_disability_only  boolean not null default false,
  add column if not exists education_min_code  text,      -- → education_levels.code，用于「我的学历能否报考」
  add column if not exists source_id           bigint,    -- → data_sources.id
  add column if not exists raw_payload         jsonb,     -- 原始抓取行，出问题可回溯
  add column if not exists is_active           boolean not null default true,
  add column if not exists created_at          timestamptz not null default now(),
  add column if not exists updated_at          timestamptz not null default now();

comment on column public.positions.is_disability_only is '是否残疾人专设岗位，列表页的核心筛选位';
comment on column public.positions.raw_payload         is '原始数据快照，字段解析出错时用于回溯';

-- 存量数据回填批次（只处理省份代码合法的岗位；未知代码不阻塞迁移）
insert into public.exam_cycles (province_code, year, category)
select distinct p.province_code, p.year, coalesce(p.position_origin, 0)
from public.positions p
join public.provinces pr on pr.code = p.province_code
where p.province_code is not null and p.year is not null
on conflict (province_code, year, category) do nothing;

update public.positions p
set cycle_id = c.id
from public.exam_cycles c
where p.cycle_id is null
  and p.province_code = c.province_code
  and p.year           = c.year
  and coalesce(p.position_origin, 0) = c.category;

-- 存量数据回填「是否专设岗位」：先按原文关键词粗判，后续由录入端复核
update public.positions
set is_disability_only = true
where is_disability_only = false
  and coalesce(other_requirements, '') ~ '(残疾|残障|无障碍|残疾人)';

-- -----------------------------------------------------------------------------
-- 3. 适配层：残疾类岗位的报考条件（本产品的核心差异点）
--    一个岗位一行；disability_types 用数组，方便 GIN 索引做「包含」筛选
-- -----------------------------------------------------------------------------
create table if not exists public.position_disability (
  position_id   bigint primary key references public.positions(id) on delete cascade,

  -- 可报考的残疾类别（多选）
  disability_types text[] not null default '{}',
  min_disability_level text,          -- 等级要求原文，如「三级及以下」「不限」

  is_exclusive  boolean default false, -- 残疾人专设岗位
  accessible_exam_room    boolean,     -- 无障碍考场
  sign_language_interpreter boolean,   -- 提供手语翻译
  assistive_device_allowed  boolean,   -- 允许使用辅助设备
  extra_time    boolean,               -- 延长考试时间
  escort_allowed boolean,              -- 允许陪同人员入场
  workplace_accommodation boolean,     -- 岗位工位/环境改造

  other_support text,                  -- 其他无障碍支持（自由文本）
  source_text   text,                  -- 公告原文摘录，结构化不了的一律留在这里

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint position_disability_types_valid check (
    disability_types <@ array['vision','hearing','speech','physical',
                              'intellectual','mental','multiple']::text[]
  )
);

comment on table public.position_disability is '岗位的残疾适配信息；disability_types 取值 vision/hearing/speech/physical/intellectual/mental/multiple';
comment on column public.position_disability.source_text is '公告原文摘录，结构化字段为空时前端优先展示这段';

-- -----------------------------------------------------------------------------
-- 4. 专业目录树：门类 → 专业类 → 专业
--    岗位绑定目录节点，「计算机类」自动覆盖其下所有专业
-- -----------------------------------------------------------------------------
create table if not exists public.majors (
  id          bigint generated by default as identity primary key,
  code        text unique,        -- 教育部专业代码
  name        text not null,
  level       smallint not null check (level in (1,2,3)),  -- 1门类 2专业类 3专业
  parent_id   bigint references public.majors(id) on delete set null,
  discipline  text,               -- 学科门类名，冗余便于直接展示
  keywords    text[] not null default '{}',  -- 别名/简称，用于模糊召回
  created_at  timestamptz not null default now()
);

comment on table public.majors is '教育部专业目录树，用于岗位专业要求的结构化匹配';

create table if not exists public.position_majors (
  position_id      bigint not null references public.positions(id) on delete cascade,
  major_id         bigint not null references public.majors(id) on delete cascade,
  requirement_kind text not null default 'allow'
                   check (requirement_kind in ('allow','exclude')),  -- 允许报考 / 明确排除
  primary key (position_id, major_id, requirement_kind)
);

comment on table public.position_majors is '岗位—专业要求关联；挂父节点即代表「本类及以下全部专业」';

