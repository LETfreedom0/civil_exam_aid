-- =============================================================================
-- positions_full：全量岗位存储表
-- 设计原则：
--   1. 字段顺序严格沿用 common/schema.sql 中原 positions 的定义顺序（45 列）
--   2. 之后是「原表漏掉 / 线上后补」的系统字段（8 列）
--   3. 最后是「残疾人适配」块（4 列，扁平化自 position_disability，便于单表筛选）
--      与「多群体 / 溯源」块（4 列）
-- 存量数据：不回填（存量保留在 positions），只建结构
-- =============================================================================

create table if not exists public.positions_full (
  -- ---------------------------------------------------------------------------
  -- 一、原 positions 表字段（顺序与 common/schema.sql 完全一致）
  -- ---------------------------------------------------------------------------
  id                      bigint generated by default as identity primary key,
  exam_region             text,        -- 考区
  recruit_unit            text,        -- 单位名称
  unit_level              text,        -- 单位层级
  position_name           text,        -- 职位名称
  position_code           text,        -- 职位代码
  position_nature         text,        -- 职位性质
  exam_subjects           text,        -- 笔试考试科目
  quota                   integer,     -- 招录人数
  candidate_identity      text,        -- 报考人员身份要求
  grassroots_exp          text,        -- 基层工作年限要求
  gender                  text,        -- 性别要求
  max_age                 text,        -- 最高年龄要求
  education               text,        -- 最低学历要求
  degree                  text,        -- 学位要求
  major                   text,        -- 专业要求
  domicile                text,        -- 户籍要求
  certification           text,        -- 职业资格证书等要求
  other_requirements      text,        -- 其他招录条件及说明
  min_service_years       text,        -- 最低服务年限要求
  exam_ratio              text,        -- 笔试最低开考比例
  physical_test_standards text,        -- 体能测评项目和标准
  medical_test_standards  text,        -- 体检标准
  phone1                  text,        -- 咨询电话1
  phone2                  text,        -- 咨询电话2
  region_dept             text,        -- 地区部门
  position_type           text,        -- 职位类别
  rank_level              text,        -- 职级层次
  political_status        text,        -- 政治面貌
  fresh_grad              text,        -- 面向应届毕业生招考
  fresh_grad_year         text,        -- 面向2026年应届毕业生招考
  exam_type               text,        -- 笔试考试类型
  essay_subject           text,        -- 申论科目(申论考试类型)
  police_subject          text,        -- 公安类专业科目
  legal_knowledge         text,        -- 法律基础知识
  physical_test           text,        -- 体能测评比例
  is_set                  text,        -- 专业能力测试是否测试
  test_ratio              text,        -- 专业能力测试比例
  interview_ratio         text,        -- 面试比例
  inspection_ratio        text,        -- 考察比例
  description             text,        -- 职位描述
  year                    integer,     -- 年份
  city                    text,        -- 城市
  province_code           text,        -- 省份代码
  position_origin         integer default 0, -- 岗位来源：0省考,1事业单位,2其他

  -- ---------------------------------------------------------------------------
  -- 二、原表漏掉 / 线上实际存在但 schema.sql 未登记的字段
  -- ---------------------------------------------------------------------------
  phone                   text,        -- 咨询电话（部分省份只有一列，落这里）
  source_id               bigint,      -- 数据源 ID（sources.yaml）
  announcement_id         bigint,      -- 公告 ID
  cycle_id                bigint,      -- 考试批次 ID（exam_cycles）
  education_min_code      text,        -- 最低学历档位代码（education_levels）
  raw_payload             jsonb,       -- 采集原始行（回溯用）
  is_active               boolean not null default true,  -- 是否上架
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),

  -- ---------------------------------------------------------------------------
  -- 三、残疾人适配字段（产品核心，扁平化便于单表查询与筛选）
  -- ---------------------------------------------------------------------------
  is_disability_only      boolean not null default false, -- 是否残疾人专岗
  disability_types        text[],      -- 适配残疾类别（vision/hearing/speech/physical/intellectual/mental/multiple/unspecified）
  allowed_levels          smallint[],  -- 允许的残疾等级（1-4）
  disability_source_text  text,        -- 公告原文中的残疾要求（保底展示）

  -- ---------------------------------------------------------------------------
  -- 四、多群体扩展与溯源
  -- ---------------------------------------------------------------------------
  audience_tags           text[] not null default '{}', -- 群体标签：disabled/veteran/fresh_grad/grassroots_project/village_cadre/minority/police_family
  remote_area             boolean,     -- 是否艰苦边远地区岗位
  source_url              text,        -- 公告来源链接（合规：标数据来源）
  external_key            text         -- 采集幂等键（省|年|代码|单位|职位名 的 md5）
);

-- -----------------------------------------------------------------------------
-- 注意：本表只建结构，不回填存量数据（存量保留在 positions）。
-- 待切换主表时再执行数据迁移，届时可参考：
--   insert into public.positions_full (...) select ... from public.positions p
--   left join public.position_disability pd on pd.position_id = p.id;
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- 索引：查询路径全部走索引
-- -----------------------------------------------------------------------------
create unique index if not exists positions_full_external_key_uidx
  on public.positions_full (external_key) where external_key is not null;

create index if not exists positions_full_province_year_idx
  on public.positions_full (province_code, year);

create index if not exists positions_full_origin_year_idx
  on public.positions_full (position_origin, year);

create index if not exists positions_full_disability_types_idx
  on public.positions_full using gin (disability_types);

create index if not exists positions_full_audience_tags_idx
  on public.positions_full using gin (audience_tags);

create index if not exists positions_full_active_idx
  on public.positions_full (is_active) where is_active;

-- 关键词搜索（职位名/单位/专业/描述）
create index if not exists positions_full_name_trgm_idx
  on public.positions_full using gin (position_name gin_trgm_ops);

-- -----------------------------------------------------------------------------
-- RLS：匿名只读（沿用收紧后的策略，不给 anon 写权限）
-- -----------------------------------------------------------------------------
alter table public.positions_full enable row level security;

drop policy if exists "Public read positions_full" on public.positions_full;
create policy "Public read positions_full"
  on public.positions_full for select using (true);
