-- =============================================================================
-- 助残公考 · 数据结构 v2.1
-- 主题：多群体扩展（残疾人优先）+ 残疾等级结构化 + 采集依赖表
--
-- 背景数据事实（2026-11-09 线上实测）：
--   positions 456 条，其中残疾人专岗 448 条（文本含"肢体四级/听力残疾四级"等）
--   candidate_identity 取值不统一：残疾人/面向残疾人/不限/应届高校毕业生…
--   (province_code, year, position_code, recruit_unit) 仍有 13 组重复 →
--     旧数据不做唯一约束，新数据由采集端生成 external_key 做幂等 upsert
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 多群体标签：残疾人是第一个群体，后面按同一套字典扩展
--    disabled         残疾人
--    veteran          退役军人
--    fresh_grad       应届毕业生
--    grassroots_project  服务基层项目人员（三支一扶/西部计划/大学生村官/特岗教师）
--    village_cadre    优秀村（社区）干部
--    minority         少数民族
--    police_family    公安英烈子女
-- -----------------------------------------------------------------------------
alter table public.positions
  add column if not exists audience_tags text[] not null default '{}';

alter table public.positions
  drop constraint if exists positions_audience_tags_valid;
alter table public.positions
  add constraint positions_audience_tags_valid check (
    audience_tags <@ array['disabled','veteran','fresh_grad',
                           'grassroots_project','village_cadre',
                           'minority','police_family']::text[]
  );

create index if not exists positions_audience_tags_gin
  on public.positions using gin (audience_tags);

-- 来源合规：详情页需展示公告来源（技术方案要求）
alter table public.positions add column if not exists source_url text;

-- 艰苦边远地区（影响开考比例与定向招录，属于可筛选属性）
alter table public.positions add column if not exists remote_area boolean;

-- 采集幂等键：省份|年份|职位代码|单位|职位名 的哈希，由采集端写入
alter table public.positions add column if not exists external_key text;
create unique index if not exists positions_external_key_uidx
  on public.positions (external_key);

-- -----------------------------------------------------------------------------
-- 2. 残疾等级结构化：文本"三、四级"→ 数组 [3,4]，才能筛"我是四级能报吗"
-- -----------------------------------------------------------------------------
alter table public.position_disability
  add column if not exists allowed_levels smallint[] not null default '{}';

alter table public.position_disability
  drop constraint if exists position_disability_levels_valid;
alter table public.position_disability
  add constraint position_disability_levels_valid check (
    allowed_levels <@ array[1,2,3,4]::smallint[]
  );

-- -----------------------------------------------------------------------------
-- 3. 采集流水线依赖表（notices 已见附件去重 / run_log 运行日志）
--    写入走 service_role（RLS 对 anon 关闭），匿名只读 run_log
-- -----------------------------------------------------------------------------
create table if not exists public.notices (
  id        bigint generated by default as identity primary key,
  url       text unique,
  title     text,
  source_id text,
  seen_at   timestamptz not null default now()
);

create table if not exists public.run_log (
  id                 bigint generated by default as identity primary key,
  source_id          text,
  change_type        text not null check (change_type in ('import','update','expire','rollback')),
  summary            text,
  affected_positions integer not null default 0,
  created_at         timestamptz not null default now()
);

alter table public.notices enable row level security;
alter table public.run_log  enable row level security;
drop policy if exists "public read notices" on public.notices;
drop policy if exists "public read run_log" on public.run_log;
create policy "public read notices" on public.notices for select using (true);
create policy "public read run_log" on public.run_log for select using (true);

-- -----------------------------------------------------------------------------
-- 4. 回填一：remote_area 与 audience_tags
--    （remote_area 先行解析，tags 回填只放群体字典内的值）
-- -----------------------------------------------------------------------------
update public.positions
set remote_area = true
where remote_area is null
  and coalesce(other_requirements,'') ~ '艰苦边远地区[:：]\s*是';

update public.positions
set remote_area = false
where remote_area is null;

update public.positions
set audience_tags = array_remove(array[
    case
      when coalesce(candidate_identity,'') ~ '残疾人' or is_disability_only
      then 'disabled'
    end,
    case
      when coalesce(fresh_grad,'') = '是'
           or coalesce(candidate_identity,'') ~ '应届'
      then 'fresh_grad'
    end
  ]::text[], null)
where audience_tags = '{}';

-- -----------------------------------------------------------------------------
-- 5. 回填二：position_disability 从文本解析
--    类型：肢体→physical 听力→hearing 视力→vision 言语→speech
--          智力→intellectual 精神→mental 多重→multiple
--    等级：抓取文本中出现的"一级~四级"全部档位；未写等级=不限（空数组）
--    原文一律保留在 source_text，解析错了可人工修正
--    先放开类型字典（引入 unspecified 占位），再回填
-- -----------------------------------------------------------------------------
alter table public.position_disability
  drop constraint if exists position_disability_types_valid;
alter table public.position_disability
  add constraint position_disability_types_valid check (
    disability_types <@ array['vision','hearing','speech','physical',
                              'intellectual','mental','multiple',
                              'unspecified']::text[]
  );

insert into public.position_disability
  (position_id, disability_types, allowed_levels, is_exclusive, source_text)
select
  p.id,
  array_remove(array[
    case when req ~ '肢体' then 'physical' end,
    case when req ~ '听力' then 'hearing'  end,
    case when req ~ '视力' then 'vision'   end,
    case when req ~ '言语' then 'speech'   end,
    case when req ~ '智力' then 'intellectual' end,
    case when req ~ '精神' then 'mental'   end,
    case when req ~ '多重' then 'multiple' end
  ]::text[], null),
  coalesce((
    select array_agg(distinct lv order by lv)::smallint[]
    from (
      select case u.lv
        when '一级' then 1 when '二级' then 2
        when '三级' then 3 when '四级' then 4 end as lv
      from regexp_matches(req, '[一二三四]级', 'g') as rm(arr)
      cross join lateral unnest(rm.arr) as u(lv)
    ) s
    where s.lv is not null
  ), '{}'),
  true,
  left(req, 500)
from public.positions p
cross join lateral (select coalesce(p.other_requirements,'') || ' ' || coalesce(p.candidate_identity,'') as req) r
where p.is_disability_only
  and req ~ '(残疾人证|限残疾人|残疾人)'
  and not exists (select 1 from public.position_disability d where d.position_id = p.id);

-- 没有类型/等级信息但有证的，也留一行占位（source_text 可查，前端展示原文）
update public.position_disability d
set disability_types = array['unspecified']::text[]
where d.disability_types = '{}'
  and exists (
    select 1 from public.positions p
    where p.id = d.position_id
      and coalesce(p.other_requirements,'') !~ '(肢体|听力|视力|言语|智力|精神|多重)'
  );

-- -----------------------------------------------------------------------------
-- 6. GIN 索引：等级/类型筛选走索引
-- -----------------------------------------------------------------------------
create index if not exists position_disability_types_gin
  on public.position_disability using gin (disability_types);
create index if not exists position_disability_levels_gin
  on public.position_disability using gin (allowed_levels);
