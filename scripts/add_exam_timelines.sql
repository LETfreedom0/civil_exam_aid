-- 创建考试时间线表
create table public.exam_timelines (
  id bigint generated by default as identity primary key,
  province_code text not null, -- 省份代码
  year integer not null, -- 年份
  category text default '公务员', -- 考试类型：公务员/事业单位
  
  -- 关键时间节点
  announcement_date date, -- 公告发布时间
  signup_start date, -- 报名开始时间
  signup_end date, -- 报名结束时间
  payment_end date, -- 缴费截止时间
  admit_card_start date, -- 准考证打印开始时间
  exam_date date, -- 笔试时间
  score_date date, -- 成绩查询时间
  interview_date_start date, -- 面试开始时间
  interview_date_end date, -- 面试结束时间
  
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 开启 RLS
alter table public.exam_timelines enable row level security;

-- 允许所有用户读取
create policy "Enable read access for all users" on public.exam_timelines for select using (true);

-- 允许所有用户插入（仅用于测试/管理员）
create policy "Enable insert access for all users" on public.exam_timelines for insert with check (true);

