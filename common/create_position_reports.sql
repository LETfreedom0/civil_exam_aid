-- 报错信息表结构设计
-- 用于存储用户对职位信息的报错反馈

-- 创建报错信息表
CREATE TABLE IF NOT EXISTS public.position_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position_id BIGINT,                      -- 关联的职位ID
  position_name TEXT,                      -- 职位名称（冗余存储）
  report_type TEXT NOT NULL,               -- 问题类型：info_error/expired/missing/other
  description TEXT,                        -- 用户补充描述
  contact_info TEXT,                       -- 联系方式（可选）
  status TEXT DEFAULT 'pending',           -- 状态：pending/processing/resolved/ignored
  admin_note TEXT,                         -- 管理员处理备注
  created_at TIMESTAMPTZ DEFAULT NOW(),    -- 提交时间
  updated_at TIMESTAMPTZ DEFAULT NOW(),    -- 更新时间
  resolved_by TEXT,                         -- 处理人
  ip_address TEXT                          -- 提交者IP（可选）
);

-- 开启 Row Level Security
ALTER TABLE public.position_reports ENABLE ROW LEVEL SECURITY;

-- 允许所有用户提交报错（仅插入）
CREATE POLICY "Allow insert for all users" ON public.position_reports 
FOR INSERT WITH CHECK (true);

-- 允许读取（所有用户可查看自己的报错记录）
CREATE POLICY "Allow read for all users" ON public.position_reports 
FOR SELECT USING (true);

-- 允许更新（管理员处理）
CREATE POLICY "Allow update for authenticated" ON public.position_reports 
FOR UPDATE USING (auth.role() = 'authenticated' OR auth.role() = 'service_role');

-- 创建索引提升查询性能
CREATE INDEX idx_position_reports_position_id ON public.position_reports(position_id);
CREATE INDEX idx_position_reports_status ON public.position_reports(status);
CREATE INDEX idx_position_reports_created_at ON public.position_reports(created_at DESC);

-- 可选：添加注释
COMMENT ON TABLE public.position_reports IS '用户职位信息报错反馈表';
COMMENT ON COLUMN public.position_reports.report_type IS '问题类型：info_error(信息有误), expired(信息过时), missing(内容缺失), other(其他)';
COMMENT ON COLUMN public.position_reports.status IS '处理状态：pending(待处理), processing(处理中), resolved(已处理), ignored(已忽略)';
