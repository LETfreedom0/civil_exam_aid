-- 创建职位表
create table public.positions (
  id bigint generated by default as identity primary key,
  exam_region text, -- 考区
  recruit_unit text, -- 单位名称
  unit_level text, -- 单位层级
  position_name text, -- 职位名称
  position_code text, -- 职位代码
  position_nature text, -- 职位性质
  exam_subjects text, -- 笔试考试科目
  quota integer, -- 招录人数
  candidate_identity text, -- 报考人员身份要求
  grassroots_exp text, -- 基层工作年限要求
  gender text, -- 性别要求
  max_age text, -- 最高年龄要求
  education text, -- 最低学历要求
  degree text, -- 学位要求
  major text, -- 专业要求
  domicile text, -- 户籍要求
  certification text, -- 职业资格证书等要求
  other_requirements text, -- 其他招录条件及说明
  min_service_years text, -- 最低服务年限要求
  exam_ratio text, -- 笔试最低开考比例
  physical_test_standards text, -- 体能测评项目和标准
  medical_test_standards text, -- 体检标准
  phone1 text, -- 咨询电话1
  phone2 text, -- 咨询电话2
  region_dept text, -- 地区部门
  position_type text, -- 职位类别
  rank_level text, -- 职级层次
  political_status text, -- 政治面貌
  fresh_grad text, -- 面向应届毕业生招考
  fresh_grad_year text, -- 面向2026年应届毕业生招考
  exam_type text, -- 笔试考试类型
  essay_subject text, -- 申论科目(申论考试类型)
  police_subject text, -- 公安类专业科目
  legal_knowledge text, -- 法律基础知识
  physical_test text, -- 体能测评比例
  is_set text, -- 专业能力测试是否测试
  test_ratio text, -- 专业能力测试比例
  interview_ratio text, -- 面试比例
  inspection_ratio text, -- 考察比例
  description text, -- 职位描述
  year integer, -- 年份
  city text, -- 城市
  province_code text, -- 省份代码
  position_origin integer default 0 -- 岗位来源：0省考,1事业单位,2其他
);

-- 开启 Row Level Security (RLS)
alter table public.positions enable row level security;

-- 允许所有用户读取数据 (根据需求调整)
create policy "Enable read access for all users" on public.positions for select using (true);

-- 允许所有用户插入数据 (仅用于数据导入脚本，生产环境建议关闭或使用 Service Role Key)
create policy "Enable insert access for all users" on public.positions for insert with check (true);

-- 创建省份表
create table public.provinces (
  code text primary key,
  name text not null
);

alter table public.provinces enable row level security;

create policy "Enable read access for all users" on public.provinces for select using (true);

